// t(key, vars) — UI strings. Falls back to English, then the key itself.
export function makeT(lang) {
  return (key, vars) => {
    let s = UI[lang]?.[key] ?? UI.en[key] ?? key;
    if (vars) for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(vars[k]);
    return s;
  };
}

// td(text) — data content (questions, tags, world names). Falls back to the original.
export function makeTD(lang) {
  return (text) => (lang === "en" ? text : DATA[lang]?.[text] ?? text);
}
